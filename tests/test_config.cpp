// test_config.cpp — geometry helpers vs Fortran/MATLAB oracles.
#include "../src/config.hpp"
#include <cmath>
#include <cstdio>
using namespace bdsim;

static int checks = 0, failures = 0;
static void expect(double got, double want, const char* what) {
    ++checks;
    if (std::fabs(got - want) > 1e-6) {
        std::printf("  [FAIL] %-20s got %.15g want %.15g\n", what, got, want);
        ++failures;
    }
}

int main() {
    Vec3Field R = {
        {4.4300450016525000e-01, -3.3196056529376028e+00, 5.6132256569023198e-01},
        {1.9030176853078951e+00, -1.2695629199997360e+00, 6.8182316538962096e-01},
        {9.1311608108670805e-01, -7.1791445684858998e-02, 8.9166947220366999e-02},
        {4.4330671786225401e-01, 8.1458593138783497e-01, -1.2960528538904701e+00},
        {-1.5134472363696660e+00, 1.2352696315890850e+00, -8.9531485574350800e-01},
        {-1.4183050785054969e+00, 1.7319540232256150e+00, 1.8692574041718699e-01},
        {-4.4785729015092501e-01, 1.1633844528360100e+00, 9.9689781373572595e-01},
        {-2.7460991831883702e-01, 6.5784188432063095e-01, -1.9640797715447600e-01},
        {3.7236102056231302e-01, 3.0421928502129097e-01, -1.4997345046665300e-01},
        {-4.2058648163949502e-01, -1.2462951897582699e+00, 2.1612904801974000e-02}};

    const double uvx[9] = {5.7944175608126003e-01, -5.9522532362554004e-01, -2.7468973561912702e-01,
                           -9.5863447079962405e-01, 7.9645677196824999e-02, 7.0016073333826800e-01,
                           1.3250236696976000e-01, 8.7574437340957700e-01, -4.5312745081482397e-01};
    const double uvy[9] = {8.1360933812326097e-01, 7.2021694922843105e-01, 5.1825013808962705e-01,
                           2.0609739688746501e-01, 4.1578586835775899e-01, -4.1021278232060898e-01,
                           -3.8664705977290498e-01, -4.7866601579109902e-01, -8.8603680503118598e-01};
    const double uvz[9] = {4.7823594888862002e-02, -3.5636268064846999e-01, -8.0991502240394098e-01,
                           1.9632578636270501e-01, 9.0596836466724595e-01, 5.8438037331176895e-01,
                           -9.1265939644337102e-01, 6.2854099056012996e-02, 9.8052503528402002e-02};
    const double cos_expected[8] = {2.2403428410843801e-01, 8.2537830865396700e-01, 2.1112985007575100e-01,
                                    1.8720624513310299e-01, 4.1463422899762298e-01, -2.8195971820794202e-01,
                                    2.4374862584760501e-01, 3.3454893589510003e-02};

    const ChainGeometry g = chain_geometry(R);
    const Vec3Field u = unit_bonds(g);
    for (size_t m = 0; m < u.size(); ++m) {
        expect(u[m][0], uvx[m], "unit bond x");
        expect(u[m][1], uvy[m], "unit bond y");
        expect(u[m][2], uvz[m], "unit bond z");
    }

    Vec3Field uref(9);
    for (int m = 0; m < 9; ++m) uref[m] = {uvx[m], uvy[m], uvz[m]};
    const std::vector<dp> cs = bond_cosines(uref);
    for (size_t i = 0; i < cs.size(); ++i) expect(cs[i], cos_expected[i], "bond cosine");

    std::printf("\nConfig/geometry: %d checks, %d failures -> %s\n",
                checks, failures, failures == 0 ? "ALL PASSED" : "FAILED");
    return failures == 0 ? 0 : 1;
}
